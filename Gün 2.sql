CREATE OR ALTER VIEW SATIS.TURKIYE_YILLARA_GORE_NET_CIRO
WITH ENCRYPTION
AS
SELECT
    M.MUSTERI_ADI,
    YEAR(S.SIPARIS_TARIHI) AS YIL,
    SUM(SD.ADET * SD.BIRIM_FIYAT * (1 - SD.INDIRIM_ORANI)) AS NET_CIRO
FROM SATIS.MUSTERILER AS M
JOIN SATIS.SIPARISLER AS S
    ON M.MUSTERI_ID = S.MUSTERI_ID
JOIN SATIS.SIPARIS_DETAY AS SD
    ON S.SIPARIS_ID = SD.SIPARIS_ID
WHERE M.ULKE = 'Türkiye'
  AND S.DURUM <> N'Ýptal'
GROUP BY M.MUSTERI_ADI, YEAR(S.SIPARIS_TARIHI);
GO

