CREATE FUNCTION SATIS.FN_YILIN_EN_COK_SATANLARI
(
	@YIL int,
	@ADET int
)
RETURNS TABLE
AS
RETURN
(
	SELECT TOP (@ADET)
		U.URUN_KODU,
		U.URUN_ADI,
		SUM(D.ADET) AS TOPLAM_ADET,
		SUM(D.ADET * D.BIRIM_FIYAT) AS CIRO
	FROM SATIS.SIPARIS_DETAY D
	JOIN SATIS.SIPARISLER S ON S.SIPARIS_ID = D.SIPARIS_ID
	JOIN URETIM.URUNLER U ON U.URUN_ID = D.URUN_ID
	WHERE YEAR(S.SIPARIS_TARIHI) = @YIL
	GROUP BY U.URUN_KODU, U.URUN_ADI
	ORDER BY CIRO DESC
);
GO

