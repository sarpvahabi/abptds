--Scalar values konusuna bakýn.

--En son teslimatýmýzý ne zaman gerçekleþtirmiþiz?
SELECT TOP 1 GERCEKLESEN_TESLIM_TARIHI
FROM SATIS.SIPARISLER
ORDER BY GERCEKLESEN_TESLIM_TARIHI DESC;
GO

--SET ANSI_NULLS ON;
--Ýlk teslimatýmýzý ne zaman gerçekleþtirmiþiz?
SELECT TOP 1 GERCEKLESEN_TESLIM_TARIHI
FROM SATIS.SIPARISLER
WHERE GERCEKLESEN_TESLIM_TARIHI IS NOT NULL
ORDER BY GERCEKLESEN_TESLIM_TARIHI ASC;
GO

--Aktif personellerimizi getiriniz, adlarýný ve yaþlarýný görmek istiyorum. Büyükten küçüðe

SELECT AD_SOYAD, DATEDIFF(year, DOGUM_TARIHI, GETDATE()) AS YAÞ
FROM IK.PERSONELLER
WHERE DOGUM_TARIHI IS NOT NULL
ORDER BY YAÞ DESC;



