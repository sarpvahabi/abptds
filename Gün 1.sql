--Geç sevk ettiðimiz sipariþler?
SELECT *
FROM SATIS.SIPARISLER
WHERE GERCEKLESEN_SEVK_TARIHI > PLANLANAN_SEVK_TARIHI;
GO

--Geç kalan sipariþler?
SELECT *
FROM SATIS.SIPARISLER
WHERE GERCEKLESEN_SEVK_TARIHI > PLANLANAN_SEVK_TARIHI
	OR GERCEKLESEN_TESLIM_TARIHI > PLANLANAN_TESLIM_TARIHI;
GO

--Bu yýl geç sevk edilen sipariþlerimiz?
SELECT *
FROM SATIS.SIPARISLER
WHERE GERCEKLESEN_SEVK_TARIHI > PLANLANAN_SEVK_TARIHI
	AND YEAR(GERCEKLESEN_SEVK_TARIHI) = YEAR(GETDATE());

--SharePoint þirket portalýmýzda bugün doðum günü olan personelleri göstermek istiyoruz. Sorgusunu yazýnýz.

